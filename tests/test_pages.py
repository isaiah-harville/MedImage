from pathlib import Path

from xpt import expect

from opendiagnostics.notebook import pages
from opendiagnostics.notebook.model import Baseline, Baselines, Project, Run
from opendiagnostics.publish import Artifact, Artifacts


def _estimate(value, lower, upper):
    return {"value": value, "lower": lower, "upper": upper, "confidence": 0.95}


def _run(run_id, auroc):
    return Run(
        project="demo",
        run_id=run_id,
        path=Path(run_id),
        config={"name": "demo"},
        record={
            "git": {"commit": "a" * 40, "branch": "main", "dirty": False},
            "started": "2026-11-26T07:00:00+00:00",
            "finished": "2026-11-26T07:02:00+00:00",
            "device": "cpu",
            "parameters": 1234,
            "seed": 0,
            "deterministic": "strict",
            "environment": {"python": "3.13", "platform": "test", "packages": {"torch": "2.15.0"}},
            "dataset": {
                "name": "medmnist",
                "license": "CC BY 4.0",
                "patient_ids_available": False,
                "fingerprint": {"md5": "abc"},
            },
        },
        metrics={
            "selection": {"monitor": "auroc", "mode": "max", "best_epoch": 3},
            "bootstrap": {
                "replicates": 2000,
                "confidence": 0.95,
                "unit": "sample (no patient IDs)",
            },
            "calibration": {"threshold": 0.5, "threshold_source": "config"},
            "val": {"auroc": _estimate(0.99, 0.98, 1.0)},
            "test": {
                "auroc": _estimate(*auroc),
                "accuracy": _estimate(0.9, 0.88, 0.92),
                "n_samples": 624,
            },
        },
        history=[],
        splits={
            "method": "predefined",
            "summary": {"test": {"samples": 624, "patients": 624, "strata": {"0": 234, "1": 390}}},
        },
        artifacts=Artifacts(
            files=[Artifact(file="checkpoint.pt", bytes=1_195_765, sha256="f" * 64)]
        ),
    )


def _project():
    baselines = Baselines(
        benchmark="Demo benchmark",
        protocol="Test AUROC on the official split.",
        baselines=[
            Baseline(
                method="Strong",
                metrics={"auroc": 0.99, "accuracy": 0.95},
                source="A 2024",
                url="https://example.org/a",
            ),
            Baseline(
                method="Tied", metrics={"auroc": 0.95}, source="B 2023", url="https://example.org/b"
            ),
            Baseline(
                method="Weak", metrics={"auroc": 0.90}, source="A 2024", url="https://example.org/a"
            ),
        ],
    )
    return Project(
        name="demo",
        path=Path("demo"),
        card="",
        config={"task": "classification", "data": {"dataset": {"name": "medmnist"}}},
        baselines=baselines,
        runs=[_run("run-2", (0.96, 0.94, 0.97)), _run("run-1", (0.93, 0.91, 0.95))],
    )


def test_metric_formatting():
    expect(
        [pages.fmt(_estimate(0.96163, 0.9442, 0.977)), pages.fmt(float("nan")), pages.fmt(0.5)],
        ["0.9616 [0.9442, 0.9770]", "n/a", "0.5000"],
    )


def test_sizes_use_binary_units():
    expect(
        [pages.size(n) for n in (None, 512, 2048, 1_195_765, 3 * 1024**3)],
        ["", "512 B", "2.0 KB", "1.1 MB", "3.0 GB"],
    )


