"""Build the lab notebook: one docs page per model project and per published run.

``build_notebook`` regenerates ``docs/notebook/`` from ``models/`` and is safe to rerun.
Small run files are copied next to each page so the site serves them for download; large
artifacts are linked from the URL recorded in each run's ``artifacts.yaml``.
"""

from __future__ import annotations

import shutil
from pathlib import Path

from opendiagnostics.notebook import pages, plots
from opendiagnostics.notebook.model import Project, Run, load_projects
from opendiagnostics.publish import EXAMPLES

MARKER = ".generated-by-opendiagnostics"


class NotebookError(RuntimeError):
    """Raised when the notebook cannot be generated safely."""


def _reset(out_dir: Path) -> None:
    if out_dir.exists():
        if any(out_dir.iterdir()) and not (out_dir / MARKER).exists():
            raise NotebookError(
                f"{out_dir} exists and was not made by `opendiagnostics notebook`; "
                "refusing to replace it. Choose an empty or generated directory."
            )
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    (out_dir / MARKER).write_text("This directory is regenerated by `opendiagnostics notebook`.\n")


def _write_run(run: Run, out_dir: Path) -> None:
    files = out_dir / "files"
    files.mkdir(parents=True)
    downloads = []
    for source in sorted(run.path.iterdir()):
        if source.is_file():
            shutil.copyfile(source, files / source.name)
            downloads.append(
                pages.Download(source.name, f"files/{source.name}", source.stat().st_size)
            )
    for artifact in run.artifacts.files:
        downloads.append(
            pages.Download(artifact.file, artifact.url or "", artifact.bytes, artifact.sha256)
        )
    if (run.path / EXAMPLES).is_dir():
        shutil.copytree(run.path / EXAMPLES, files / EXAMPLES)
    figures = []
    if run.history:
        plots.training_curves(run.history, run.monitor, files / "training.svg")
        figures.append(("Training curves", "training.svg"))
    test_csv = run.path / "predictions_test.csv"
    if test_csv.exists() and plots.roc_and_pr(test_csv, files / "roc_pr.svg"):
        figures.append(("ROC and precision-recall on test", "roc_pr.svg"))
    (out_dir / "index.md").write_text(pages.run_page(run, figures, downloads))


def _write_project(project: Project, out_dir: Path) -> None:
    out_dir.mkdir(parents=True)
    (out_dir / "index.md").write_text(pages.project_page(project))
    for run in project.runs:
        _write_run(run, out_dir / run.run_id)


def build_notebook(models_dir: Path, out_dir: Path) -> list[Project]:
    projects = load_projects(Path(models_dir))
    out_dir = Path(out_dir)
    _reset(out_dir)
    (out_dir / "index.md").write_text(pages.index_page(projects))
    for project in projects:
        _write_project(project, out_dir / project.name)
    return projects


__all__ = ["NotebookError", "build_notebook"]
