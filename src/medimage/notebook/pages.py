"""Render notebook pages as Markdown. Pure functions: data in, text out."""

from __future__ import annotations

import math
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any

import yaml

from medimage.notebook.model import Baseline, Project, Run

GENERATED = "<!-- Generated by `medimage notebook`. Edit the run files or the generator. -->\n"


@dataclass(frozen=True)
class Download:
    label: str
    href: str
    size: int | None = None
    sha256: str | None = None


def fmt(value: Any) -> str:
    """A metric as ``0.9616 [0.9480, 0.9737]``, or ``n/a`` when undefined."""
    if isinstance(value, dict) and "value" in value:
        point = fmt(value["value"])
        if not math.isfinite(value["lower"]):
            return point
        return f"{point} [{value['lower']:.4f}, {value['upper']:.4f}]"
    if isinstance(value, float):
        return "n/a" if not math.isfinite(value) else f"{value:.4f}"
    return str(value)


def size(n: int | None) -> str:
    if n is None:
        return ""
    if n < 1024:
        return f"{n} B"
    value = n / 1024
    for unit in ("KB", "MB"):
        if value < 1024:
            return f"{value:.1f} {unit}"
        value /= 1024
    return f"{value:.1f} GB"


def table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(cell.replace("|", "\\|") for cell in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def headline_metrics(run: Run) -> list[str]:
    test = run.metrics.get("test", {})
    return [k for k, v in test.items() if isinstance(v, dict) and "/" not in k]


def versus(baseline: Baseline, metric: str, best: dict[str, Any] | None) -> str:
    """Where a published number sits against our best run's confidence interval."""
    if best is None or metric not in baseline.metrics:
        return ""
    value = baseline.metrics[metric]
    if value > best["upper"]:
        return "above our CI"
    if value < best["lower"]:
        return "below our CI"
    return "inside our CI"


def leaderboard(project: Project) -> str:
    """Our runs and published baselines ranked by the project's headline test metric."""
    if not project.runs:
        return "No published runs yet.\n"
    metric = project.runs[0].monitor
    extra = "accuracy"
    rows: list[tuple[float, list[str]]] = []
    for run in project.runs:
        head = run.headline()
        if head is None:
            continue
        acc = run.metrics["test"].get(extra)
        rows.append(
            (
                head["value"],
                [
                    f"**[{run.run_id}]({run.run_id}/index.md)** (ours)",
                    fmt(head),
                    fmt(acc) if acc else "",
                    "",
                ],
            )
        )
    heads = [head for run in project.runs if (head := run.headline()) is not None]
    best = max(heads, key=lambda head: head["value"], default=None)
    for baseline in project.baselines.baselines if project.baselines else []:
        if metric not in baseline.metrics:
            continue
        rows.append(
            (
                baseline.metrics[metric],
                [
                    f"[{baseline.method}]({baseline.url})",
                    fmt(baseline.metrics[metric]),
                    fmt(baseline.metrics[extra]) if extra in baseline.metrics else "",
                    versus(baseline, metric, best),
                ],
            )
        )
    rows.sort(key=lambda r: -r[0])
    text = table(
        ["Method", f"Test {metric} [95% CI]", f"Test {extra}", "Published value vs our best"],
        [r[1] for r in rows],
    )
    if project.baselines:
        text += f"\nBenchmark: {project.baselines.benchmark}. {project.baselines.protocol}\n"
        sources = sorted({b.source for b in project.baselines.baselines})
        text += "\nBaseline sources: " + "; ".join(sources) + ".\n"
    text += (
        "\nA published number outside our interval is a difference worth acting on; one inside it"
        " is not. A claim that one of our runs beats another uses `medimage compare`, a paired"
        " patient-level bootstrap on the same test samples.\n"
    )
    return text


def index_page(projects: Sequence[Project]) -> str:
    rows = []
    for project in projects:
        latest = project.runs[0] if project.runs else None
        head = latest.headline() if latest else None
        rows.append(
            [
                f"[{project.name}]({project.name}/index.md)",
                str(project.config["data"]["dataset"]["name"]),
                str(
                    project.config["task"]
                    if isinstance(project.config["task"], str)
                    else project.config["task"]["name"]
                ),
                str(len(project.runs)),
                f"{latest.monitor} {fmt(head)}" if latest and head else "no runs",
            ]
        )
    return (
        GENERATED + "# Lab notebook\n\n"
        "Every trained model has a project, and every published run has a page with its config, "
        "metrics with 95% patient-level bootstrap intervals, training curves, provenance, and "
        "downloadable artifacts. Pages are generated from the files under `models/`.\n\n"
        + table(["Project", "Dataset", "Task", "Runs", "Latest test result"], rows)
    )


def project_page(project: Project) -> str:
    runs = [
        [
            f"[{r.run_id}]({r.run_id}/index.md)",
            r.record.get("started", ""),
            (r.record.get("git", {}).get("commit") or "")[:8],
            fmt(r.headline()) if r.headline() else "",
        ]
        for r in project.runs
    ]
    card = project.card.strip()
    return (
        GENERATED
        + f"# {project.name}\n\n"
        + "## Leaderboard\n\n"
        + leaderboard(project)
        + "\n## Runs\n\n"
        + (
            table(["Run", "Started (UTC)", "Commit", "Test headline"], runs)
            if runs
            else "None yet.\n"
        )
        + ("\n## Model card\n\n" + _demote(card) + "\n" if card else "")
    )


def _demote(markdown: str) -> str:
    """Shift headings down two levels so an included card nests under this page's sections."""
    return "\n".join(
        "##" + line if line.startswith("#") else line for line in markdown.splitlines()
    )


def run_page(run: Run, plots: Sequence[tuple[str, str]], downloads: Sequence[Download]) -> str:
    record, metrics = run.record, run.metrics
    git = record.get("git", {})
    env = record.get("environment", {})
    dataset = record.get("dataset", {})
    names = headline_metrics(run)
    splits = [s for s in ("val", "test") if s in metrics]
    metric_rows = [
        [name] + [fmt(metrics[s].get(name, float("nan"))) for s in splits] for name in names
    ]
    per_class = sorted({k for s in splits for k in metrics[s] if "/" in k})
    split_rows = [
        [
            name,
            str(v.get("samples", "")),
            str(v.get("patients", "")),
            ", ".join(f"{k}: {n}" for k, n in v.get("strata", {}).items()),
        ]
        for name, v in run.splits.get("summary", {}).items()
    ]
    calibration = metrics.get("calibration", {})
    boot = metrics.get("bootstrap", {})
    selection = metrics.get("selection", {})
    parts = [
        GENERATED,
        f"# {run.run_id}\n\n",
        f"Project [{run.project}](../index.md). ",
        f"Commit `{git.get('commit')}` on `{git.get('branch')}`"
        + (" (**uncommitted changes**)" if git.get("dirty") else " (clean tree)")
        + f". Started {record.get('started')}, finished {record.get('finished')}, on `{record.get('device')}`. "
        f"{record.get('parameters', 0):,} parameters.\n\n",
        "## Results\n\n",
        f"Checkpoint from epoch {selection.get('best_epoch')}, chosen on validation `{selection.get('monitor')}` "
        f"({selection.get('mode')}). Intervals are {boot.get('replicates')}-replicate percentile bootstrap at "
        f"{boot.get('confidence')}, resampling by {boot.get('unit')}.",
        (
            f" Decision threshold {calibration['threshold']:.4f} ({calibration.get('threshold_source')})."
            if "threshold" in calibration
            else ""
        ),
        "\n\n",
        table(["Metric"] + [f"{s} [95% CI]" for s in splits], metric_rows),
    ]
    if per_class:
        rows = [
            [name] + [fmt(metrics[s].get(name, float("nan"))) for s in splits] for name in per_class
        ]
        parts += [
            '\n??? note "Per-class metrics"\n\n',
            _indent(table(["Metric", *splits], rows)),
            "\n",
        ]
    for title, file in plots:
        parts.append(f"\n![{title}](files/{file})\n")
    parts += [
        "\n## Data\n\n",
        f"Dataset `{dataset.get('name')}`, license {dataset.get('license')}. Split method `{run.splits.get('method')}`. "
        + (
            ""
            if dataset.get("patient_ids_available")
            else "The dataset has no patient IDs, so patient-level leakage could not be checked. "
        )
        + "\n\n",
        table(["Split", "Samples", "Patients", "Label counts"], split_rows),
        f"\nFingerprint: `{_inline(dataset.get('fingerprint', {}))}`.\n",
        (f"\nCitation: {dataset['citation']}\n" if dataset.get("citation") else ""),
        "\n## Reproduce\n\n",
        f"```bash\ngit checkout {git.get('commit')}\nuv sync --locked --extra cpu\n"
        f"uv run medimage train models/{run.project}/config.yaml\n```\n\n",
        f"Seed {record.get('seed')}, deterministic mode `{record.get('deterministic')}`, "
        f"Python {env.get('python')} on {env.get('platform')}.\n\n",
        table(
            ["Package", "Version"], [[k, str(v)] for k, v in env.get("packages", {}).items() if v]
        ),
        '\n??? note "Resolved config"\n\n',
        _indent("```yaml\n" + yaml.safe_dump(run.config, sort_keys=False) + "```\n"),
        "\n## Downloads\n\n",
        table(
            ["File", "Size", "SHA-256"],
            [
                [
                    f"[{d.label}]({d.href})" if d.href else f"{d.label} (not uploaded yet)",
                    size(d.size),
                    f"`{d.sha256}`" if d.sha256 else "",
                ]
                for d in downloads
            ],
        ),
    ]
    return "".join(parts)


def _indent(text: str) -> str:
    return "".join(
        "    " + line if line.strip() else line for line in text.splitlines(keepends=True)
    )


def _inline(value: dict[str, Any]) -> str:
    return ", ".join(f"{k}={v}" for k, v in value.items())
