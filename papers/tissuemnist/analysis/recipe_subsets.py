"""Compare the shared MedMNIST 2D recipe's first run on every subset with that subset's best
published value, so the paper can say how TissueMNIST was picked from the twelve.

    uv run python -I papers/tissuemnist/analysis/recipe_subsets.py

Reads models/*-convnext/ projects written by scripts/medmnist_recipes.py and writes
generated/tables/subsets.tex and generated/subsets.tex (macros).
"""

from __future__ import annotations

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
PAPER = Path(__file__).resolve().parents[1]
MARKER = "Generated by scripts/medmnist_recipes.py"


def display(flag: str) -> str:
    """``organamnist`` becomes ``OrganAMNIST``, ``bloodmnist`` becomes ``BloodMNIST``."""
    name = flag.removesuffix("mnist")
    if name.startswith("organ"):
        return f"Organ{name[5:].upper()}MNIST"
    return f"{name.capitalize()}MNIST"


def rows() -> list[dict]:
    out = []
    for config in sorted(ROOT.glob("models/*-convnext/config.yaml")):
        if MARKER not in config.read_text():
            continue
        project = config.parent
        runs = sorted((project / "runs").iterdir())
        if not runs:
            raise SystemExit(f"{project.name} has no published run")
        first = runs[0]
        metrics = json.loads((first / "metrics.json").read_text())
        monitor = metrics["selection"]["monitor"].removeprefix("val/")
        test = metrics["test"][monitor]
        baselines = yaml.safe_load((project / "baselines.yaml").read_text())["baselines"]
        best = max(
            (b for b in baselines if monitor in b["metrics"]), key=lambda b: b["metrics"][monitor]
        )
        out.append(
            {
                "subset": yaml.safe_load(config.read_text())["data"]["init_args"]["flag"],
                "run": first.name,
                "metric": monitor,
                "value": test["value"],
                "lower": test["lower"],
                "upper": test["upper"],
                "best": best["metrics"][monitor],
            }
        )
    return out


def main() -> None:
    found = rows()
    if len(found) != 12:
        raise SystemExit(f"expected the 12 MedMNIST 2D subsets, found {len(found)}")
    lines = []
    for row in found:
        verdict = (
            "above"
            if row["lower"] > row["best"]
            else "below"
            if row["upper"] < row["best"]
            else "inside"
        )
        row["verdict"] = verdict
        lines.append(
            f"{display(row['subset'])} & "
            f"{row['value']:.4f} [{row['lower']:.4f}, {row['upper']:.4f}] & {row['best']:.4f} & "
            f"{verdict} \\\\"
        )
        print(
            row["subset"],
            row["run"],
            f"{row['value']:.4f}",
            f"{row['lower']:.4f}",
            row["best"],
            verdict,
        )
    above = [r["subset"] for r in found if r["verdict"] == "above"]
    point = sum(r["value"] > r["best"] for r in found)
    macros = {
        "subsetsAbove": str(len(above)),
        "subsetsPointAbove": str(point),
        "subsetsTotal": str(len(found)),
    }
    (PAPER / "generated").mkdir(exist_ok=True)
    (PAPER / "generated/subsets.tex").write_text(
        "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()) + "\n"
    )
    commits = {r["run"][-8:-1] for r in found}
    if len(commits) != 1:
        raise SystemExit(f"first runs trained at several commits: {commits}")
    commit = commits.pop()
    body = "\n".join(lines)
    (PAPER / "generated/tables/subsets.tex").write_text(
        "\\begin{table}[t]\n"
        "\\caption{How does the same recipe do on the other MedMNIST 2D subsets? Test AUROC of the "
        f"first run (seed 0, all at commit {commit}) on each subset at 224 pixels, with its 95\\% bootstrap interval, against "
        "the best published value in that project's \\texttt{baselines.yaml}. Only the "
        "ChestMNIST, DermaMNIST, and TissueMNIST lists have had a literature review. Our CI: whether our interval lies "
        "above or below that value, or contains it.}\n"
        "\\label{tab:subsets}\n\\centering\n\\footnotesize\n\\setlength{\\tabcolsep}{3pt}\n"
        "\\begin{tabular}{@{}llll@{}}\n\\toprule\n"
        "Subset & Ours [95\\% CI] & Published & Our CI \\\\\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n\\end{{table}}\n"
    )
    print(macros, "above:", above)


if __name__ == "__main__":
    main()
